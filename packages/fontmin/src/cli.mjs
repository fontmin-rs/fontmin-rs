function parseUnicodeRanges(values) {
  return values.map(value => parseUnicodeRange(value))
}

function formatUnicodeEndpoint(codePoint) {
  return codePoint.toString(16).toUpperCase().padStart(4, '0')
}

function parseUnicodeRange(value) {
  const match =
    /^u\+(?<start>[0-9a-f]{1,6})(?:-(?<end>[0-9a-f]{1,6}))?$/iu.exec(value)

  if (match?.groups === undefined) {
    throw new Error(`invalid Unicode range: ${value}`)
  }

  const start = Number.parseInt(match.groups.start, 16)
  const end = Number.parseInt(match.groups.end ?? match.groups.start, 16)

  if (start > end || end > 0x10_ff_ff || (start <= 0xdf_ff && end >= 0xd8_00)) {
    throw new Error(`invalid Unicode range: ${value}`)
  }

  return start === end
    ? `U+${formatUnicodeEndpoint(start)}`
    : `U+${formatUnicodeEndpoint(start)}-${formatUnicodeEndpoint(end)}`
}

function parseDeliverySlices(values) {
  const slices = []

  for (const value of values) {
    const separator = value.indexOf(':')

    if (separator === -1) {
      throw new Error(`delivery slice must use NAME:RANGE[,RANGE...]: ${value}`)
    }

    const name = value.slice(0, separator)
    const unicodeRanges = value.slice(separator + 1).split(',')
    const existing = slices.find(slice => slice.name === name)

    if (existing === undefined) {
      slices.push({ name, unicodeRanges })
    } else {
      existing.unicodeRanges.push(...unicodeRanges)
    }
  }

  return normalizeDeliverySlices(slices)
}

function parseAutoDeliveryOptions(values) {
  const requested =
    values.enabled ||
    values.frequencyText !== undefined ||
    values.languages !== undefined ||
    values.maxSlices !== undefined ||
    values.measureFormat !== undefined ||
    values.targetBytes !== undefined ||
    values.tolerance !== undefined
  if (!requested) {
    return
  }

  const languages = values.languages?.split(',').map(language => {
    const normalized = language.trim()
    if (
      ![
        'ar',
        'el',
        'en',
        'hi',
        'ja',
        'ko',
        'ru',
        'zh-Hans',
        'zh-Hant',
      ].includes(normalized)
    ) {
      throw new Error(`unsupported delivery language \`${normalized}\``)
    }
    return normalized
  })
  if (languages?.some(language => language.length === 0) === true) {
    throw new Error('--delivery-languages must not be empty')
  }
  if (
    values.measureFormat !== undefined &&
    !['ttf', 'woff', 'woff2'].includes(values.measureFormat)
  ) {
    throw new Error(
      `unsupported --delivery-measure-format \`${values.measureFormat}\`; expected ttf, woff, or woff2`,
    )
  }
  const maxSlices = parseOptionalPositiveInteger(
    values.maxSlices,
    '--delivery-max-slices',
  )
  if (maxSlices !== undefined && maxSlices > 256) {
    throw new Error('--delivery-max-slices must be at most 256')
  }
  const targetBytes = parseOptionalPositiveInteger(
    values.targetBytes,
    '--delivery-target-bytes',
  )
  const tolerance =
    values.tolerance === undefined ? undefined : Number(values.tolerance)
  if (
    tolerance !== undefined &&
    (!Number.isFinite(tolerance) || tolerance < 0 || tolerance >= 1)
  ) {
    throw new Error('--delivery-tolerance must be in [0, 1)')
  }

  return {
    ...(values.frequencyText === undefined
      ? {}
      : { frequencyText: values.frequencyText }),
    ...(languages === undefined ? {} : { languages }),
    ...(maxSlices === undefined ? {} : { maxSlices }),
    ...(values.measureFormat === undefined
      ? {}
      : { measureFormat: values.measureFormat }),
    ...(targetBytes === undefined ? {} : { targetBytes }),
    ...(tolerance === undefined ? {} : { tolerance }),
  }
}

function parseOptionalPositiveInteger(value, option) {
  if (value === undefined) {
    return
  }
  if (!/^[1-9][0-9]*$/u.test(value)) {
    throw new TypeError(`${option} must be a positive integer`)
  }
  const parsed = Number(value)
  if (!Number.isSafeInteger(parsed)) {
    throw new TypeError(`${option} must be a safe positive integer`)
  }

  return parsed
}

function normalizeDeliverySlices(values) {
  return normalizeRuntimeDeliverySlices(values, { allowEmpty: true }).map(
    slice => ({
      name: slice.name,
      unicodeRanges: parseUnicodeRanges(slice.unicodeRanges),
    }),
  )
}

function parseUnicodes(value) {
  if (value === undefined) {
    return []
  }

  const unicodes = value.split(',').map(item => parseUnicodeCodePoint(item))

  if (unicodes.length === 0) {
    throw new Error('expected at least one unicode code point')
  }

  return unicodes
}

function parseUnicodeCodePoint(value) {
  const item = value.trim()

  if (item.length === 0) {
    throw new Error('empty unicode code point in --unicodes')
  }

  let digits = item
  let radix = 10

  if (/^(?:0x|u\+)/iu.test(item)) {
    digits = item.slice(2)
    radix = 16
  }

  const validDigits = radix === 16 ? /^[0-9a-f]+$/iu : /^[0-9]+$/u

  if (!validDigits.test(digits)) {
    throw new Error(`invalid unicode code point \`${item}\``)
  }

  const codePoint = Number.parseInt(digits, radix)

  if (!Number.isInteger(codePoint) || codePoint > 4_294_967_295) {
    throw new Error(`invalid unicode code point \`${item}\``)
  }

  return codePoint
}

function parseGids(value) {
  if (value === undefined) {
    return []
  }

  return value.split(',').map(item => parseGid(item))
}

function parseU16List(value, flag) {
  if (value === undefined) {
    return []
  }

  return value.split(',').map(value => parseU16(value, flag))
}

function parseGlyphNames(value) {
  return parseStringList(value, '--glyph-names', 'glyph name')
}

function parseStringList(value, flag, itemName = 'OpenType tag') {
  if (value === undefined) {
    return []
  }

  return value.split(',').map(item => {
    const parsed = item.trim()

    if (parsed.length === 0) {
      throw new Error(`empty ${itemName} in ${flag}`)
    }

    return parsed
  })
}

function parseTableTags(value, flag) {
  const tags = parseStringList(value, flag, 'OpenType table tag').map(tag =>
    tag.length === 3 ? `${tag} ` : tag,
  )

  for (const tag of tags) {
    if (!/^[ -~]{4}$/u.test(tag)) {
      throw new Error(
        `OpenType table tag \`${tag}\` in ${flag} must be three or four printable ASCII bytes`,
      )
    }
  }

  return tags
}

function parseGid(value) {
  return parseU16(value, '--gids', 'glyph ID')
}

function parseU16(value, flag, itemName = 'numeric ID') {
  const item = value.trim()

  if (item.length === 0) {
    throw new Error(`empty ${itemName} in ${flag}`)
  }

  const hexadecimal = /^0x/iu.test(item)
  const digits = hexadecimal ? item.slice(2) : item
  const validDigits = hexadecimal ? /^[0-9a-f]+$/iu : /^[0-9]+$/u

  if (!validDigits.test(digits)) {
    throw new Error(`invalid ${itemName} \`${item}\` in ${flag}`)
  }

  const parsed = hexadecimal ? Number.parseInt(digits, 16) : Number(digits)

  if (!Number.isInteger(parsed) || parsed > 65_535) {
    throw new Error(`invalid ${itemName} \`${item}\` in ${flag}`)
  }

  return parsed
}

function parseFormats(value) {
  const formats = value
    .split(',')
    .map(format => format.trim().toLowerCase())
    .filter(format => format.length > 0)

  if (formats.length === 0) {
    throw new Error('expected at least one output format')
  }

  for (const format of formats) {
    if (
      format !== 'ttf' &&
      format !== 'woff' &&
      format !== 'woff2' &&
      format !== 'eot' &&
      format !== 'svg' &&
      format !== 'css'
    ) {
      throw new Error(`unsupported output format \`${format}\``)
    }
  }

  return formats
}

function convertFont(contents, format, options = {}) {
  const normalized = format.toLowerCase()

  if (normalized === 'ttf') {
    if (isTtf(contents)) {
      return contents
    }

    if (isWoff(contents)) {
      return woffToTtf(contents)
    }

    if (isWoff2(contents)) {
      return woff2ToTtf(contents)
    }

    if (isEot(contents)) {
      return eotToTtf(contents)
    }

    if (isOtf(contents)) {
      return otfToTtf(contents, {
        variationCoordinates: options.variationCoordinates ?? {},
      })
    }

    throw new Error('unsupported input format for TTF conversion')
  }

  const ttf = convertFont(contents, 'ttf', options)

  if (normalized === 'woff') {
    return ttfToWoff(ttf)
  }

  if (normalized === 'woff2') {
    return ttfToWoff2(ttf)
  }

  if (normalized === 'eot') {
    return ttfToEot(ttf)
  }

  if (normalized === 'svg') {
    return ttfToSvg(ttf)
  }

  throw new Error(`unsupported output format \`${format}\``)
}

function isTtf(contents) {
  return (
    (contents[0] === 0x00 &&
      contents[1] === 0x01 &&
      contents[2] === 0x00 &&
      contents[3] === 0x00) ||
    contents.subarray(0, 4).toString('ascii') === 'true'
  )
}

function isOtf(contents) {
  return contents.subarray(0, 4).toString('ascii') === 'OTTO'
}

function isWoff(contents) {
  return contents.subarray(0, 4).toString('ascii') === 'wOFF'
}

function isWoff2(contents) {
  return contents.subarray(0, 4).toString('ascii') === 'wOF2'
}

function isEot(contents) {
  return (
    contents.byteLength >= 12 &&
    ((contents[8] === 0x01 &&
      contents[9] === 0x00 &&
      contents[10] === 0x02 &&
      contents[11] === 0x00) ||
      (contents[8] === 0x02 &&
        contents[9] === 0x00 &&
        contents[10] === 0x02 &&
        contents[11] === 0x00))
  )
}

function readOption(args, names) {
  const index = args.findIndex(arg => names.includes(arg))

  if (index === -1) {
    return
  }

  const [name] = args.splice(index, 1)
  const [value] = args.splice(index, 1)

  if (value === undefined || value.startsWith('-')) {
    throw new Error(`${name} requires a value`)
  }

  return value
}

function readOptions(args, names) {
  const values = []

  while (args.some(arg => names.includes(arg))) {
    values.push(readOption(args, names))
  }

  return values
}

function readFlag(args, names) {
  const index = args.findIndex(arg => names.includes(arg))

  if (index === -1) {
    return false
  }

  args.splice(index, 1)
  return true
}

function assertNoUnknownOptions(args) {
  const option = args.find(arg => arg.startsWith('-'))

  if (option !== undefined) {
    throw new Error(`unknown option \`${option}\``)
  }
}

function assertNoUnexpectedArgs(args, maximumPositionals = 1) {
  assertNoUnknownOptions(args)

  if (args.length > maximumPositionals) {
    throw new Error(`unexpected argument \`${args[maximumPositionals]}\``)
  }
}

function parseVariations(values) {
  const coordinates = {}

  for (const value of values) {
    const separator = value.indexOf('=')

    if (separator === -1) {
      throw new Error(`invalid variation \`${value}\`; expected TAG=VALUE`)
    }

    const tag = value.slice(0, separator)
    const rawNumber = value.slice(separator + 1)

    if (
      tag.length !== 4 ||
      [...tag].some(character => (character.codePointAt(0) ?? 128) > 127)
    ) {
      throw new Error(
        `invalid variation axis \`${tag}\`; expected four ASCII characters`,
      )
    }
    if (Object.hasOwn(coordinates, tag)) {
      throw new Error(`duplicate variation axis \`${tag}\``)
    }

    const number = Number(rawNumber)

    if (rawNumber.length === 0 || !Number.isFinite(number)) {
      throw new Error(
        `invalid variation value \`${rawNumber}\` for axis \`${tag}\``,
      )
    }

    coordinates[tag] = number
  }

  return coordinates
}

function parseVariationRanges(values) {
  const ranges = {}

  for (const value of values) {
    const separator = value.indexOf('=')

    if (separator === -1) {
      throw new Error(
        `invalid variation range \`${value}\`; expected TAG=MIN:MAX[:DEFAULT]`,
      )
    }
    const tag = value.slice(0, separator)
    const rawRange = value.slice(separator + 1)

    if (
      tag.length !== 4 ||
      [...tag].some(character => (character.codePointAt(0) ?? 128) > 127)
    ) {
      throw new Error(
        `invalid variation axis \`${tag}\`; expected four ASCII characters`,
      )
    }
    if (Object.hasOwn(ranges, tag)) {
      throw new Error(`duplicate variation axis \`${tag}\``)
    }

    const parts = rawRange.split(':')
    if (parts.length < 2 || parts.length > 3) {
      throw new Error(
        `invalid variation range \`${rawRange}\` for axis \`${tag}\`; expected MIN:MAX[:DEFAULT]`,
      )
    }
    const numbers = parts.map(rawNumber => {
      const number = Number(rawNumber)

      if (rawNumber.length === 0 || !Number.isFinite(number)) {
        throw new Error(
          `invalid variation range value \`${rawNumber}\` for axis \`${tag}\``,
        )
      }

      return number
    })
    const [min, max, defaultValue] = numbers

    ranges[tag] = {
      ...(defaultValue === undefined ? {} : { default: defaultValue }),
      max,
      min,
    }
  }

  return ranges
}

function requireValue(value, message) {
  if (value === undefined || value.length === 0) {
    throw new Error(message)
  }
}

async function writeOutput(output, contents) {
  await mkdir(dirname(output), { recursive: true })
  await writeFile(output, contents)
}

