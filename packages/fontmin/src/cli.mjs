async function buildConfigInput(
  input,
  outDir,
  outputFormats,
  config,
  cwd,
  cacheOptions,
  variationCoordinates,
) {
  const subset = await resolveSubsetTextFile(config.subset ?? {}, cwd)
  const baseName = basename(input, extname(input))
  const slices = normalizeDeliverySlices(config.delivery?.slices ?? [])
  const plugins = [normalizeToTtfPlugin(variationCoordinates)]

  if (hasSubsetRequest(subset)) {
    plugins.push(glyph(subset))
  }
  if (slices.length > 0) {
    plugins.push(deliverySlicesPlugin(slices))
  }
  if (Array.isArray(config.plugins)) {
    plugins.push(...config.plugins)
  }

  await optimize({
    autoDelivery: config.autoDelivery,
    cache: cacheOptions,
    css: {
      ...config.css,
      fontFamily: config.css?.fontFamily ?? baseName,
    },
    cwd,
    input: [input],
    outDir,
    outputs: outputConfigsForFormats(config.outputs, outputFormats),
    plugins,
    preserveOriginal: config.preserveOriginal,
    runtime: config.runtime,
  })
}

