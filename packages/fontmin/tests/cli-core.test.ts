it('exposes the frozen public command surface through the package bin', () => {
  const contract = JSON.parse(
    readFileSync(
      resolve(currentDir, '../../../contracts/public-api.json'),
      'utf8',
    ),
  ) as {
    cli: {
      commands: Record<
        string,
        { flags: string[]; shortFlags: string[]; positionals: string[] }
      >
      globalFlags: string[]
    }
  }
  const help = execFileSync(process.execPath, [bin, '--help'], {
    encoding: 'utf8',
  })
  const commands = [
    ...help.matchAll(/^\s*fontmin-rs (?<command>[a-z]+)(?:\s|$)/gmu),
  ]
    .map(match => match.groups?.['command'])
    .filter(command => command !== undefined)

  expect([...new Set(commands)].toSorted()).toStrictEqual(
    Object.keys(contract.cli.commands).toSorted(),
  )

  for (const [command, surface] of Object.entries(contract.cli.commands)) {
    const commandUsage = help
      .split('\n')
      .filter(line => line.trimStart().startsWith(`fontmin-rs ${command}`))
      .join('\n')

    expect(flagsFromUsage(commandUsage)).toStrictEqual(
      [...surface.flags, ...surface.shortFlags].toSorted(),
    )
    for (const positional of surface.positionals) {
      expect(commandUsage.toUpperCase()).toContain(`<${positional}`)
    }
  }

  for (const flag of contract.cli.globalFlags) {
    expect(() => execFileSync(process.execPath, [bin, flag])).not.toThrow()
  }
})

it('initializes a JSONC config through the package bin', () => {
  const workDir = mkdtempSync(resolve(tmpdir(), 'fontmin-rs-bin-init-'))
  const configPath = resolve(workDir, 'fontmin.config.jsonc')

  try {
    const packageDir = resolve(workDir, 'node_modules/fontmin-rs')

    mkdirSync(packageDir, { recursive: true })
    writeFileSync(resolve(packageDir, 'configuration_schema.json'), '{}')

    const stdout = execFileSync(process.execPath, [bin, 'init'], {
      cwd: workDir,
      encoding: 'utf8',
    })
    const config = readFileSync(configPath, 'utf8')

    expect(stdout).toContain('fontmin.config.jsonc')
    expect(config).toContain('Generated by fontmin-rs init')
    expect(config).toContain(
      '"$schema": "./node_modules/fontmin-rs/configuration_schema.json"',
    )
    expect(config).toContain('"input"')
    expect(config).toContain('"outputs"')
    expect(config).toContain('"woff2"')
    expect(config).toContain('"fontDisplay": "swap"')
    expect(config).toContain('"cache"')

    mkdirSync(resolve(workDir, 'fonts'))
    writeFileSync(
      resolve(workDir, 'fonts/roboto-regular.ttf'),
      readFileSync(fixture),
    )
    execFileSync(process.execPath, [bin, 'build', '--config', configPath], {
      cwd: workDir,
    })

    const woff2 = readFileSync(resolve(workDir, 'build/roboto-regular.woff2'))
    const woff = readFileSync(resolve(workDir, 'build/roboto-regular.woff'))

    expect(woff2.subarray(0, 4).toString('ascii')).toBe('wOF2')
    expect(woff.subarray(0, 4).toString('ascii')).toBe('wOFF')
    expect(
      readFileSync(resolve(workDir, 'build/roboto-regular.css'), 'utf8'),
    ).toContain("font-family: 'MyFont';")
  } finally {
    rmSync(workDir, { recursive: true, force: true })
  }
})

