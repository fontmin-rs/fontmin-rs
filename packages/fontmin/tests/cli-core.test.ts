it('selects collection faces across package bin font commands', () => {
  const workDir = mkdtempSync(resolve(tmpdir(), 'fontmin-rs-bin-collection-'))
  const source = readFileSync(fixture)
  const collectionPath = resolve(workDir, 'fonts.ttc')
  const variableCollectionPath = resolve(workDir, 'variable.ttc')
  const subsetPath = resolve(workDir, 'subset.ttf')
  const woffPath = resolve(workDir, 'font.woff')
  const instancePath = resolve(workDir, 'instance.ttf')

  try {
    writeFileSync(collectionPath, fontCollection([source, source]))
    writeFileSync(
      variableCollectionPath,
      fontCollection([readFileSync(variableTtfFixture)]),
    )

    const inventory = JSON.parse(
      execFileSync(
        process.execPath,
        [bin, 'inspect', collectionPath, '--json'],
        {
          encoding: 'utf8',
        },
      ),
    ) as { faces: unknown[]; format: string }
    expect(inventory.format).toBe('collection')
    expect(inventory.faces).toHaveLength(2)

    execFileSync(process.execPath, [
      bin,
      'subset',
      collectionPath,
      '--font-number',
      '1',
      '--text',
      'Hello',
      '--output',
      subsetPath,
    ])
    expect(inspect(readFileSync(subsetPath)).format).toBe('ttf')

    const coverage = JSON.parse(
      execFileSync(
        process.execPath,
        [
          bin,
          'coverage',
          collectionPath,
          '--font-number',
          '0',
          '--text',
          'A',
          '--json',
        ],
        { encoding: 'utf8' },
      ),
    ) as { supported: number[] }
    expect(coverage.supported).toStrictEqual([0x41])

    execFileSync(process.execPath, [
      bin,
      'convert',
      collectionPath,
      '--font-number',
      '0',
      '--format',
      'woff',
      '--output',
      woffPath,
    ])
    expect(readFileSync(woffPath).subarray(0, 4).toString('ascii')).toBe('wOFF')

    const bench = JSON.parse(
      execFileSync(
        process.execPath,
        [
          bin,
          'bench',
          collectionPath,
          '--font-number',
          '0',
          '--text',
          'A',
          '--json',
        ],
        { encoding: 'utf8' },
      ),
    ) as { operation: string }
    expect(bench.operation).toBe('subset')

    execFileSync(process.execPath, [
      bin,
      'instance',
      variableCollectionPath,
      '--font-number',
      '0',
      '--output',
      instancePath,
    ])
    expect(inspect(readFileSync(instancePath)).metadata.tables).not.toContain(
      'fvar',
    )
  } finally {
    rmSync(workDir, { recursive: true, force: true })
  }
})

it('subsets by glyph ID and writes a mapping report through the package bin', () => {
  const outputDir = mkdtempSync(
    resolve(tmpdir(), 'fontmin-rs-bin-subset-gids-'),
  )
  const output = resolve(outputDir, 'roboto-subset.ttf')
  const reportPath = resolve(outputDir, 'roboto-subset.json')

  try {
    execFileSync(process.execPath, [
      bin,
      'subset',
      fixture,
      '-o',
      output,
      '--text',
      'A',
      '--gids',
      '1,65535',
      '--glyph-names',
      'A,does.not.exist',
      '--layout-features',
      'liga',
      '--layout-scripts',
      'latn',
      '--layout-languages',
      'default',
      '--name-ids',
      '1',
      '--name-languages',
      '0x409',
      '--drop-tables',
      'GPOS',
      '--pass-through-tables',
      'gasp',
      '--retain-gids',
      '--retain-glyph-names',
      '--retain-legacy-cmap',
      '--retain-symbol-cmap',
      '--report',
      reportPath,
    ])

    const report = JSON.parse(readFileSync(reportPath, 'utf8')) as {
      glyphsRetained: number
      glyphNameToOldGid: { glyphName: string; oldGid: number }[]
      missingGids: number[]
      missingGlyphNames: string[]
      newToOld: (number | null)[]
      oldToNew: { newGid: number; oldGid: number }[]
      requestedGids: number[]
      requestedGlyphNames: string[]
      supportedGids: number[]
      supportedGlyphNames: string[]
    }

    expect(inspect(readFileSync(output)).metadata.glyphCount).toBe(39)
    expect(inspect(readFileSync(output)).metadata.tables).not.toContain('GPOS')
    expect(inspect(readFileSync(output)).metadata.tables).toContain('gasp')
    expect(sfntTableVersion(readFileSync(output), 'post')).toBe(0x0002_0000)
    expect(hasCmapRecord(readFileSync(output), 1, 0)).toBe(true)
    expect(report).toMatchObject({
      glyphsRetained: 39,
      missingGids: [65_535],
      missingGlyphNames: ['does.not.exist'],
      requestedGids: [1, 65_535],
      requestedGlyphNames: ['A', 'does.not.exist'],
      supportedGids: [1],
      supportedGlyphNames: ['A'],
    })
    expect(report.glyphNameToOldGid).toContainEqual({
      glyphName: 'A',
      oldGid: 38,
    })
    expect(report.oldToNew).toContainEqual({ newGid: 38, oldGid: 38 })
    expect(report.newToOld[2]).toBeNull()
  } finally {
    rmSync(outputDir, { recursive: true, force: true })
  }
})

